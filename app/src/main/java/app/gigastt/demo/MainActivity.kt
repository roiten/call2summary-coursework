package app.gigastt.demo

import android.app.Activity
import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import android.content.Intent
import android.net.Uri
import android.os.Bundle
import android.provider.OpenableColumns
import android.view.View
import android.webkit.MimeTypeMap
import android.widget.Button
import android.widget.ProgressBar
import android.widget.TextView
import android.widget.Toast
import uniffi.gigastt_uniffi.Engine // generated by build_native.sh
import java.io.File
import java.net.UnknownHostException
import java.util.concurrent.Executors

class MainActivity : Activity() {

    private lateinit var status: TextView
    private lateinit var fileName: TextView
    private lateinit var result: TextView
    private lateinit var progress: ProgressBar
    private lateinit var btnDownload: Button
    private lateinit var btnPick: Button
    private lateinit var btnRecognize: Button
    private lateinit var btnCopy: Button

    private val worker = Executors.newSingleThreadExecutor()
    private var pickedUri: Uri? = null
    private var pickedName: String = ""

    companion object {
        private const val REQ_PICK = 1
        // Kept in a static so it survives Activity re-creation; loading takes seconds.
        @Volatile private var engine: Engine? = null
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContentView(R.layout.activity_main)
        status = findViewById(R.id.status)
        fileName = findViewById(R.id.fileName)
        result = findViewById(R.id.result)
        progress = findViewById(R.id.progress)
        btnDownload = findViewById(R.id.btnDownload)
        btnPick = findViewById(R.id.btnPick)
        btnRecognize = findViewById(R.id.btnRecognize)
        btnCopy = findViewById(R.id.btnCopy)

        btnDownload.setOnClickListener { startDownload() }
        btnPick.setOnClickListener { pickFile() }
        btnRecognize.setOnClickListener { startRecognize() }
        btnCopy.setOnClickListener { copyResult() }
        refreshIdle()
    }

    override fun onDestroy() {
        worker.shutdown()
        super.onDestroy()
    }

    // ---- UI state -------------------------------------------------------

    private fun refreshIdle() {
        progress.visibility = View.INVISIBLE
        val ready = ModelStore.isReady(this)
        btnDownload.visibility = if (ready) View.GONE else View.VISIBLE
        btnDownload.isEnabled = true
        btnPick.isEnabled = true
        btnRecognize.isEnabled = ready && pickedUri != null
        status.text = if (ready) "Модель готова (локально). Интернет не нужен."
        else "Модель не загружена. Нужна одноразовая загрузка (~305 МБ, интернет)."
    }

    private fun setBusy(message: String) {
        progress.visibility = View.VISIBLE
        status.text = message
        btnDownload.isEnabled = false
        btnPick.isEnabled = false
        btnRecognize.isEnabled = false
    }

    private fun ui(block: () -> Unit) = runOnUiThread { if (!isDestroyed) block() }

    private fun showError(title: String, e: Throwable) {
        val msg = when {
            e is UnknownHostException || e.cause is UnknownHostException ->
                "Нет подключения к интернету. Он нужен только для первой загрузки модели."
            e is UnsatisfiedLinkError || e.javaClass.name.startsWith("com.sun.jna") ->
                "Не удалось загрузить нативную библиотеку gigastt/onnxruntime: ${e.message}"
            e.javaClass.name.contains("InvalidAudio") ->
                "Не удалось прочитать аудио (формат не поддерживается или файл повреждён): ${e.message}"
            e.javaClass.name.contains("ModelNotFound") ->
                "Не удалось загрузить модель: ${e.message}. Очистите данные приложения и загрузите модель заново."
            else -> "${e.javaClass.simpleName}: ${e.message}"
        }
        ui {
            refreshIdle()
            status.text = "$title\n$msg"
        }
    }

    // ---- Model download -------------------------------------------------

    private fun startDownload() {
        setBusy("Загрузка модели…")
        worker.execute {
            try {
                ModelStore.download(this) { p -> ui { status.text = p } }
                ui { refreshIdle() }
            } catch (t: Throwable) {
                showError("Ошибка загрузки модели", t)
            }
        }
    }

    // ---- File picking ---------------------------------------------------

    @Suppress("DEPRECATION")
    private fun pickFile() {
        val i = Intent(Intent.ACTION_OPEN_DOCUMENT).apply {
            addCategory(Intent.CATEGORY_OPENABLE)
            type = "*/*"
            putExtra(Intent.EXTRA_MIME_TYPES, arrayOf("audio/*", "application/ogg", "video/webm"))
        }
        startActivityForResult(i, REQ_PICK)
    }

    @Deprecated("Deprecated in Java")
    override fun onActivityResult(requestCode: Int, resultCode: Int, data: Intent?) {
        super.onActivityResult(requestCode, resultCode, data)
        if (requestCode != REQ_PICK || resultCode != RESULT_OK) return
        val uri = data?.data ?: return
        pickedUri = uri
        pickedName = displayName(uri)
        fileName.text = pickedName
        refreshIdle()
    }

    private fun displayName(uri: Uri): String =
        contentResolver.query(uri, arrayOf(OpenableColumns.DISPLAY_NAME), null, null, null)?.use {
            if (it.moveToFirst()) it.getString(0) else null
        } ?: "audio"

    /** The decoder takes a hint from the file extension, so keep it. */
    private fun extensionFor(uri: Uri, name: String): String {
        val fromName = name.substringAfterLast('.', "")
        if (fromName.isNotEmpty() && fromName.length <= 5) return fromName
        val mime = contentResolver.getType(uri)
        return MimeTypeMap.getSingleton().getExtensionFromMimeType(mime) ?: "bin"
    }

    // ---- Recognition ----------------------------------------------------

    private fun startRecognize() {
        val uri = pickedUri ?: return
        val name = pickedName
        setBusy("Распознаю и разделяю спикеров…")
        result.text = ""

        worker.execute {
            val tmp = File(cacheDir, "input." + extensionFor(uri, name))
            try {
                contentResolver.openInputStream(uri)!!.use { input ->
                    tmp.outputStream().use { input.copyTo(it) }
                }
                val e = engine ?: Engine(ModelStore.dir(this).absolutePath).also { engine = it }
                val t0 = System.currentTimeMillis()

                // Получаем детальный транскрипт со списком слов и разметкой спикеров
                val transcript = e.transcribeFile(tmp.absolutePath)
                val sec = (System.currentTimeMillis() - t0) / 1000.0

                // Группируем слова по спикерам
                val diarizedText = buildDiarizedString(transcript.words)
                val speakers = transcript.words.mapNotNull { it.speaker }.distinct().size

                ui {
                    refreshIdle()
                    result.text = diarizedText.ifBlank { "(речь не найдена)" }
                    status.text = if (speakers > 0)
                        "Готово за %.1f с (аудио %.1f с). Спикеров: %d."
                            .format(sec, transcript.durationS, speakers)
                    else
                        "Готово за %.1f с (аудио %.1f с). Спикеры не определены."
                            .format(sec, transcript.durationS)
                }
            } catch (t: Throwable) {
                showError("Ошибка распознавания", t)
            } finally {
                tmp.delete()
            }
        }
    }

    /**
     * Собирает реплики из пословных меток спикеров. Гасит одиночные
     * переключения, тянет спикера через слова без метки и склеивает реплики
     * одного спикера, если пауза между ними меньше секунды.
     */
    private fun buildDiarizedString(words: List<uniffi.gigastt_uniffi.Word>): String {
        if (words.isEmpty()) return ""
        if (words.none { it.speaker != null }) return words.joinToString(" ") { it.text }

        val speakers = words.map { it.speaker }.toMutableList()
        for (i in 1 until speakers.size - 1) {
            val prev = speakers[i - 1]
            val next = speakers[i + 1]
            if (prev != null && prev == next) speakers[i] = prev
        }
        var last = speakers.firstOrNull { it != null }
        for (i in speakers.indices) {
            val s = speakers[i]
            if (s == null) speakers[i] = last else last = s
        }

        val numbering = LinkedHashMap<UInt, Int>()
        val sb = StringBuilder()
        var i = 0
        while (i < words.size) {
            val speaker = speakers[i]!!
            var end = words[i].endS
            val text = StringBuilder(words[i].text)
            var j = i + 1
            while (j < words.size && speakers[j] == speaker && words[j].startS - end < 1.0) {
                text.append(' ').append(words[j].text)
                end = words[j].endS
                j++
            }
            val number = numbering.getOrPut(speaker) { numbering.size + 1 }
            if (sb.isNotEmpty()) sb.append("\n\n")
            sb.append("Спикер $number (${"%.1f".format(words[i].startS)}–${"%.1f".format(end)} с):\n")
            sb.append(text.toString().trim())
            i = j
        }
        return sb.toString()
    }

    private fun copyResult() {
        val text = result.text?.toString().orEmpty()
        if (text.isBlank()) {
            Toast.makeText(this, "Нечего копировать", Toast.LENGTH_SHORT).show()
            return
        }
        val cm = getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
        cm.setPrimaryClip(ClipData.newPlainText("transcript", text))
        Toast.makeText(this, "Скопировано", Toast.LENGTH_SHORT).show()
    }
}
